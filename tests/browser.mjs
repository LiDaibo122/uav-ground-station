import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile, readFile } from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/home/ldb/.cache/ms-playwright/chromium-1140/chrome-linux/chrome',args:['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader','--disable-dev-shm-usage']});
const report={checks:[],pageErrors:[]};
const check=(name,condition)=>{assert.ok(condition,name);report.checks.push(name);console.log('PASS',name);};
const originalTasks=await readFile('runs/tasks.json','utf8').catch(()=>'[]');
try{
  const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
  page.on('pageerror',e=>report.pageErrors.push(e.message));
  page.on('response',async response=>{if(response.url().endsWith('/api/chat'))report.qwen=await response.json();});
  await page.goto('http://127.0.0.1:11843',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.fieldlink?.state?.aircraft.length===3);
  await page.waitForFunction(()=>window.fieldlink.map.highestTerrainLevel>=11,{},{timeout:120000});
  await page.waitForTimeout(8000);
  const geo=await page.evaluate(()=>({terrain:fieldlink.map.highestTerrainLevel,failures:fieldlink.map.terrainFailures,tiles:fieldlink.map.viewer.scene.globe._surface._tilesToRender.map(t=>t.level)}));
  report.geography=geo;
  check('Real remote elevation decoded to level >= 11',geo.terrain>=11);
  check('No terrain fetch failures',geo.failures===0);
  check('Chinese font is bundled and loaded',await page.evaluate(()=>document.fonts.check('12px FieldLinkSC')));
  check('Three demonstration aircraft',await page.locator('.aircraft-row').count()===3);
  await page.locator('.aircraft-row[data-id="UAV-02"]').click();
  check('Aircraft selection changes telemetry card',await page.locator('#selected-id').textContent()==='UAV-02');
  await page.locator('#home-view').click();
  await page.waitForTimeout(2000);
  await page.screenshot({path:'runs/desktop.png'});
  await page.locator('#mode-switch').click();
  await page.waitForFunction(()=>fieldlink.mode==='live'&&fieldlink.state.mode==='live');
  check('Live mode removes demonstration aircraft',await page.locator('.aircraft-row').count()===0);
  check('Live scene has no demo entities',await page.evaluate(()=>fieldlink.map.aircraft.size===0));
  await page.locator('#mode-switch').click();await page.waitForFunction(()=>fieldlink.state.aircraft.length===3);
  await page.locator('#settings-button').click();
  await page.locator('input[value="google"]').check();
  await page.locator('#apply-settings').click();
  check('Google missing key is explicit', (await page.locator('#settings-error').textContent()).includes('API Key'));
  check('Missing key preserves real terrain',await page.evaluate(()=>fieldlink.map.source==='terrain'));
  await page.locator('input[value="terrain"]').check();await page.locator('#apply-settings').click();
  await page.locator('#search-button').click();await page.locator('#location-input').fill('999, 100');await page.locator('#location-form button').click();
  check('Invalid coordinates rejected',(await page.locator('#location-error').textContent()).includes('有效'));
  await page.keyboard.press('Escape');
  await page.locator('#nav-help').click();
  check('Sensor stream is explicitly disconnected',await page.locator('.sensor-placeholder').isVisible());
  await page.locator('[data-tab="chat"]').click();
  await page.locator('#chat-input').fill('请为 A 区生成一份河谷巡检草案，重点观察积水情况，常规优先级，暂不指定飞机。');
  await page.locator('#chat-send').click();
  await page.waitForFunction(()=>!document.querySelector('#chat-send').disabled,{},{timeout:190000});
  check('Actual Qwen generated a draft',await page.locator('#messages .draft-card').count()===1);
  await page.locator('#messages .draft-card button').click();
  await page.waitForFunction(()=>document.querySelector('#messages .draft-card button').textContent.includes('已保存'));
  check('Saved draft is explicitly not dispatched',(await page.locator('#messages .draft-card button').textContent()).includes('未下发'));
  await page.screenshot({path:'runs/qwen-interaction.png'});
  check('No desktop horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(1800);
  check('No mobile horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'runs/mobile.png',fullPage:true});
  check('No unhandled browser errors',report.pageErrors.length===0);
}finally{
  await writeFile('runs/browser-report.json',JSON.stringify(report,null,2));
  await writeFile('runs/tasks.json',originalTasks);
  await browser.close();
}
